"""おみくじのティア定義と項目別選択肢データ。

【追加方法】
`OMIKUJI_TIERS` 内の各ティアにある `categories` の各項目（"和歌", "願望", ...）に
文字列を1行ずつ追加するだけで簡単に選択肢を増やせます。
例:
    "願望": (
        "いい感じ",
        "ここに新しい選択肢を追加",
    ),

【確率・ティア変更】
各 `OmikujiTier` の `probability`（%）を変更することで排出確率を調整できます。
合計が 100 でない場合でも、抽選時に自動で合計 100% にスケーリングされます。
"""

