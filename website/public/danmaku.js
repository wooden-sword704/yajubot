function initDanmaku() {
  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  if (!DANMAKU_COMMENTS.length) return;

  const layer = document.createElement('div');
  layer.className = 'danmaku-layer';
  layer.setAttribute('aria-hidden', 'true');
  document.body.appendChild(layer);

  const LANE_COUNT = 6;
  const MAX_ACTIVE = 1919;
  let recentLanes = [];
  let activeCount = 0;

  const pickLane = () => {
    const candidates = [];
    for (let i = 0; i < LANE_COUNT; i++) {
      if (!recentLanes.includes(i)) candidates.push(i);
    }
    const pool = candidates.length ? candidates : Array.from({ length: LANE_COUNT }, (_, i) => i);
    const lane = pool[Math.floor(Math.random() * pool.length)];
    recentLanes.push(lane);
    if (recentLanes.length > 3) recentLanes.shift();
    return lane;
  };

  const spawnComment = () => {
    if (document.hidden || activeCount >= MAX_ACTIVE) return;

    const text = DANMAKU_COMMENTS[Math.floor(Math.random() * DANMAKU_COMMENTS.length)];
    const el = document.createElement('span');
    el.className = 'danmaku-item';
    el.textContent = text;

    const lane = pickLane();
    const topPercent = 10 + (lane / LANE_COUNT) * 72;
    const durationSec = (10 + Math.random() * 5) / 1.5;

    el.style.top = `${topPercent}%`;
    el.style.animationDuration = `${durationSec}s`;

    activeCount++;
    layer.appendChild(el);

    el.addEventListener('animationend', () => {
      el.remove();
      activeCount--;
    });
  };

  const scheduleNext = () => {
    const delayMs = 200 + Math.random() * 260;
    window.setTimeout(() => {
      spawnComment();
      scheduleNext();
    }, delayMs);
  };

  window.setTimeout(() => {
    spawnComment();
    scheduleNext();
  }, 500);
}

document.addEventListener('DOMContentLoaded', initDanmaku);
